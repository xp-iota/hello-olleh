"""The single authoring source for the twelve-episode course.

One episode per capability module (M01-M12). Every episode is built the same way, because the
same shape is what makes it usable as a lesson:

1. ``task``     — what the student will finish, the command to copy, the result to expect.
                  This is the first frame, so the first ten seconds already carry all three.
2. ``terminal`` — the real output of that command, taken from the captured evidence log.
3. ``dsh``      — the mechanism inside the runtime shell, tied to lines the student can open.
4. ``iota``     — the same task one layer out, including what that layer refuses to own.
5. ``debug``    — the error a student actually hits, how to locate it, and the fix.
6. ``exercise`` — a hands-on change plus the command that proves the answer.

``narration`` is what the voice track says; it never talks about how this course, its examples
or its documents were produced. It talks about code, commands, output and boundaries.
"""

