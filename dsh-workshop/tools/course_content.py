def episode(
    number: int,
    module: str,
    slug: str,
    title: str,
    *,
    task: str,
    command: str,
    expect: str,
    evidence: str,
    slides: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "number": number,
        "id": f"E{number:02d}",
        "module": module,
        "slug": slug,
        "title": title,
        "task": task,
        "command": command,
        "expect": expect,
        "evidence": evidence,
        "slides": slides,
    }


def task_slide(number: int, task: str, command: str, expect: str, narration: str) -> dict[str, Any]:
    return {
        "id": f"e{number:02d}-task",
        "type": "task",
        "eyebrow": f"第 {number} 集 · 本集任务",
        "title": task.split("；")[0],
        "task": task,
        "command": command,
        "expect": expect,
        "narration": narration,
        "minDurationSec": 12,
    }


def terminal_slide(
    number: int, title: str, command: str, evidence: str, narration: str, *, lines: int = 8
) -> dict[str, Any]:
    return {
        "id": f"e{number:02d}-terminal",
        "type": "terminal",
        "eyebrow": "真实输出",
        "title": title,
        "command": command,
        "evidence": evidence,
        "evidenceLines": lines,
        "narration": narration,
        "minDurationSec": 20,
    }


def body_slide(
    number: int,
    kind: str,
    eyebrow: str,
    title: str,
    narration: str,
    *,
    body: str | None = None,
    bullets: list[str] | None = None,
    nodes: list[dict[str, str]] | None = None,
    stats: list[dict[str, str]] | None = None,
    callout: str | None = None,
) -> dict[str, Any]:
    slide: dict[str, Any] = {
        "id": f"e{number:02d}-{kind}",
        "type": "diagram" if nodes else "overview" if stats else "text",
        "eyebrow": eyebrow,
        "title": title,
        "narration": narration,
        "minDurationSec": 20,
    }
    for key, value in (("body", body), ("bullets", bullets), ("nodes", nodes),
                       ("stats", stats), ("callout", callout)):
        if value is not None:
            slide[key] = value
    return slide


def debug_slide(
    number: int, title: str, symptom: str, locate: str, fix: str, narration: str
) -> dict[str, Any]:
    return {
        "id": f"e{number:02d}-debug",
        "type": "debug",
        "eyebrow": "错误定位",
        "title": title,
        "symptom": symptom,
        "locate": locate,
        "fix": fix,
        "narration": narration,
        "minDurationSec": 20,
    }


def exercise_slide(
    number: int, title: str, change: str, verify: str, answer: str, narration: str
) -> dict[str, Any]:
    return {
        "id": f"e{number:02d}-exercise",
        "type": "exercise",
        "eyebrow": "动手练习",
        "title": title,
        "change": change,
        "verify": verify,
        "answer": answer,
        "narration": narration,
        "minDurationSec": 20,
    }


def code_slide(
    number: int, title: str, locate: str, look: str, narration: str
) -> dict[str, Any]:
    """指给学员一条能立刻打开的代码位置，而不是让他们全仓库搜。"""
    return {
        "id": f"e{number:02d}-code",
        "type": "code",
        "eyebrow": "代码在哪",
        "title": title,
        "locate": locate,
        "look": look,
        "narration": narration,
        "minDurationSec": 20,
    }


